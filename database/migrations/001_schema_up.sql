-- FTTH: definición de datos (DDL).
-- PostgreSQL ejecuta este archivo al crear un volumen nuevo.

BEGIN;

CREATE TABLE IF NOT EXISTS ftth_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio TEXT NOT NULL UNIQUE,
    type TEXT NOT NULL,
    priority TEXT NOT NULL,
    crew TEXT NOT NULL,
    description TEXT NOT NULL,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    created_by TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS ftth_requests_created_at_idx
    ON ftth_requests (created_at DESC);

CREATE TABLE IF NOT EXISTS ftth_module_items (
    module TEXT NOT NULL,
    id BIGINT NOT NULL,
    name TEXT NOT NULL,
    detail TEXT NOT NULL,
    status TEXT NOT NULL,
    map_type TEXT,
    map_zone TEXT,
    map_x DOUBLE PRECISION,
    map_y DOUBLE PRECISION,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (module, id)
);

CREATE INDEX IF NOT EXISTS ftth_module_items_module_updated_idx
    ON ftth_module_items (module, updated_at DESC);

-- Evita condiciones de carrera al crear IDs independientes por módulo.
CREATE TABLE IF NOT EXISTS ftth_module_counters (
    module TEXT PRIMARY KEY,
    last_id BIGINT NOT NULL CHECK (last_id >= 0)
);

COMMIT;
